"""SIMULATED GST registry for the synthetic fixtures.

Our fictional vendors cannot exist in the real GST registry, so the demo
policy accepts a labelled `simulated_registry` method. It only knows the exact
synthetic GSTINs generated by fixtures/generate.py; anything else returns
not_found (never a fabricated match). A demo toggle simulates an outage.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache

from ..config import BACKEND_ROOT

SOURCE = "Simulated GST registry (synthetic test data — not a real lookup)"


@dataclass
class RegistryAnswer:
    result: str  # found | not_found | unavailable
    observed: dict | None


class _State:
    """Demo outage switch, per buyer (one buyer's reviewer can't affect another's). In memory: resets on restart."""

    def __init__(self):
        self.outage = False  # global switch, tests only
        self.outage_buyers: set[int] = set()

    def is_out(self, buyer_id: int | None) -> bool:
        return self.outage or (buyer_id in self.outage_buyers)

    def set_outage(self, buyer_id: int, on: bool) -> None:
        (self.outage_buyers.add if on else self.outage_buyers.discard)(buyer_id)


state = _State()


@lru_cache
def _records() -> dict:
    p = BACKEND_ROOT / "fixtures" / "out" / "simulated_registry.json"
    if not p.exists():
        return {}
    return json.loads(p.read_text(encoding="utf-8")).get("gstin", {})


def lookup_gstin(gstin: str, buyer_id: int | None = None) -> RegistryAnswer:
    if state.is_out(buyer_id):
        return RegistryAnswer("unavailable", None)
    rec = _records().get(gstin)
    if rec is None:
        return RegistryAnswer("not_found", None)
    return RegistryAnswer("found", dict(rec))
